# Timing
# --------------------------------------------------------------------------

def build_timeline(recipe, layer_names, duration):
    """[{'effect', 'direction', 'start', 'dur'}] per layer, bottom first.

    The backdrop comes on first; the rest follow one after another in
    stacking order and are all in place within the opening part of the clip
    (never more than about 45% of it, or six seconds), which then holds: a
    schedule has to be on screen, complete, long enough to be read."""
    n = len(layer_names)
    k = SPEEDS.get(recipe.get('speed'), 1.0)
    lead = 0.25
    bg = dict(recipe['background'], start=lead, dur=min(1.0, max(0.4, 0.7 * k)))
    if n <= 1:
        bg['dur'] = min(max(0.8, 1.6 * k), duration * 0.4)
        return [bg]
    rest = n - 1
    window = min(duration * 0.45, 6.0, max(1.2, rest * 0.9)) * k
    window = min(window, duration * 0.6)
    each = float(np.clip(window / rest * 1.6, 0.35, 1.2 * max(k, 1.0)))
    gap = (window - each) / (rest - 1) if rest > 1 else 0.0
    first = bg['start'] + bg['dur'] * 0.6
    out = [bg]
    for i, name in enumerate(layer_names[1:]):
        c = recipe['layers'].get(name.lower(), recipe['default'])
        out.append(dict(c, start=first + i * max(gap, 0.0), dur=each))
    return out


def settle_time(timeline):
    """When the last layer has finished arriving."""
    return max(t['start'] + t['dur'] for t in timeline)


# --------------------------------------------------------------------------
# Drawing
# --------------------------------------------------------------------------

def paste(dst, px, x, y, opacity=1.0):
    """Composites a premultiplied BGRA crop onto `dst` (BGR or premultiplied
    BGRA) at (x, y), clipped to it. In place."""
    dh, dw = dst.shape[:2]
    h, w = px.shape[:2]
    x0, y0, x1, y1 = max(0, x), max(0, y), min(dw, x + w), min(dh, y + h)
    if x1 <= x0 or y1 <= y0 or opacity <= 0:
        return
    src = px[y0 - y:y1 - y, x0 - x:x1 - x]
    if opacity < 1.0:
        src = (src.astype(np.float32) * float(opacity) + 0.5).astype(np.uint8)
    inv = 255 - src[:, :, 3:4].astype(np.uint16)
    region = dst[y0:y1, x0:x1]
    c = region.shape[2]
    region[:] = (src[:, :, :c].astype(np.uint16) + (region.astype(np.uint16) * inv + 127) // 255).clip(0, 255).astype(np.uint8)


def ease_out(u):
    u = min(1.0, max(0.0, u))
    return 1.0 - (1.0 - u) ** 3


def ease_out_back(u):
    u = min(1.0, max(0.0, u))
    c1 = 1.70158
    return 1.0 + (c1 + 1.0) * (u - 1.0) ** 3 + c1 * (u - 1.0) ** 2


def _wipe(px, u, direction):
    """The crop with everything past the wipe's edge made transparent. The
    edge is soft (a few percent of the layer) and travels across the LAYER,
    not the frame, so a small caption wipes on in the same time as a full
    width bar instead of popping on as a frame-wide wipe happens to pass."""
    h, w = px.shape[:2]
    horizontal = direction in ('left', 'right')
    n = w if horizontal else h
    soft = max(6.0, 0.08 * n)
    pos = np.arange(n, dtype=np.float32)
    if direction in ('left', 'up'):
        pos = (n - 1) - pos
    ramp = np.clip((u * (n + soft) - pos) / soft, 0.0, 1.0)
    mask = ramp[None, :, None] if horizontal else ramp[:, None, None]
    return (px.astype(np.float32) * mask + 0.5).astype(np.uint8)


def _jitter(layer_index, step):
    """A couple of pixels of repeatable wobble for one layer on one stepped
    frame -- the registration error of an object moved by hand between
    exposures."""
    rng = np.random.default_rng(1000003 * (layer_index + 1) + int(step))
    return int(rng.integers(-3, 4)), int(rng.integers(-2, 3))


class Animator:
    """Draws any moment of the animation: frame(t) -> BGR at canvas size.

    Layers that have finished arriving are baked into one picture as time
    advances, so the long hold at the end costs a copy per frame rather than
    a full composite. frame() is therefore meant to be called with rising t
    (rewinding works, it just rebuilds)."""

    def __init__(self, artwork, timeline, recipe, duration, canvas=CANVAS):
        self.layers, self.timeline, self.recipe = artwork['layers'], timeline, recipe
        self.duration, self.canvas = float(duration), canvas
        self.settled_at = settle_time(timeline)
        self._base = np.zeros((canvas[1], canvas[0], 3), np.uint8)
        self._baked = 0
        self._last_t = -1.0

    def _reset(self):
        self._base[:] = 0
        self._baked = 0

    def _draw_layer(self, dst, i, t, step):
        ly, tl = self.layers[i], self.timeline[i]
        if t < tl['start']:
            return
        raw = (t - tl['start']) / tl['dur'] if tl['dur'] > 0 else 1.0
        px, x, y = ly['px'], ly['x'], ly['y']
        if raw >= 1.0 or tl['effect'] == 'cut':
            paste(dst, px, x, y)
            return
        u = ease_out(raw)
        dx = dy = 0
        if self.recipe.get('stop_motion'):
            dx, dy = _jitter(i, step)
        effect, direction = tl['effect'], tl['direction']
        if effect == 'wipe':
            paste(dst, _wipe(px, u, direction), x + dx, y + dy)
        elif effect == 'slide':
            travel = 0.16 * (self.canvas[0] if direction in ('left', 'right') else self.canvas[1])
            off = int(round((1.0 - u) * travel))
            sx = {'right': -off, 'left': off}.get(direction, 0)
            sy = {'down': -off, 'up': off}.get(direction, 0)
            paste(dst, px, x + sx + dx, y + sy + dy, opacity=min(1.0, raw * 2.5))
        elif effect == 'pop':
            s = 0.8 + 0.2 * ease_out_back(raw)
            h, w = px.shape[:2]
            nw, nh = max(1, int(round(w * s))), max(1, int(round(h * s)))
            scaled = cv2.resize(px, (nw, nh), interpolation=cv2.INTER_LINEAR)
            paste(dst, scaled, x + (w - nw) // 2 + dx, y + (h - nh) // 2 + dy, opacity=min(1.0, raw * 3.0))
        else:                                                   # fade
            paste(dst, px, x + dx, y + dy, opacity=u)

    def frame(self, t):
        t = min(max(0.0, float(t)), self.duration)
        stop = bool(self.recipe.get('stop_motion'))
        # Stop motion steps time itself while things are arriving. Once the
        # picture is complete it holds dead still: a schedule that keeps
        # twitching for twenty seconds is not charming, it is unreadable.
        step = int(math.floor(t * STOP_MOTION_FPS + 1e-6))
        ta = min(step / STOP_MOTION_FPS, t) if stop and t < self.settled_at + 1.0 / STOP_MOTION_FPS else t
        if ta < self._last_t:
            self._reset()
        self._last_t = ta
        while self._baked < len(self.layers):
            tl = self.timeline[self._baked]
            if ta < tl['start'] + tl['dur'] and not (tl['effect'] == 'cut' and ta >= tl['start']):
                break
            ly = self.layers[self._baked]
            paste(self._base, ly['px'], ly['x'], ly['y'])
            self._baked += 1
        out = self._base.copy()
        for i in range(self._baked, len(self.layers)):
            self._draw_layer(out, i, ta, step)
        if self.recipe.get('push_in'):
            tp = (step / STOP_MOTION_FPS if stop else t) / self.duration
            s = 1.0 + PUSH_IN * min(1.0, max(0.0, tp))
            w, h = self.canvas
            m = np.float32([[s, 0, (1 - s) * w / 2.0], [0, s, (1 - s) * h / 2.0]])
            out = cv2.warpAffine(out, m, (w, h), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REPLICATE)
        return out


