"""Schedule Plug -- core logic.

Turns one still -- a flat image, or a layered Photoshop file -- into a short
animated 16:9 clip with a music bed: the weekly-schedule graphic that used to
need a motion designer for ten seconds of "bring the lines on one by one".

Deliberately has NO Flask and NO imports from the rest of PRISM, like
shorts_core.py: everything takes plain values and returns plain values.

The animation is drawn here, frame by frame, and piped to ffmpeg -- not
generated by a video model. A schedule is text (titles, dates, times) and a
generative model repaints every pixel of every frame, so the one thing the
graphic exists to say would arrive warped. Drawing it means every layer's
pixels are the designer's own, only moved, faded or uncovered, and the last
frame is the artwork exactly.

  1. load_artwork() reads the file into layers, bottom first. A PSD's
     top-level layers become the things that animate; anything else is one
     layer. If the layers can't be put back together to match the file's
     own flattened picture (blend modes, adjustment layers, effects), the
     flattened picture is used as a single layer instead: a plainer
     animation of the right image beats a livelier one of the wrong image.
  2. a recipe says how layers arrive: parse_prompt() reads the editor's
     words directly, and a language model, when one is available, can refine
     that into per-layer choices (parse_recipe_reply()).
  3. build_timeline() spaces the layers out over the opening part of the
     clip, and Animator.frame() draws any moment of it.
  4. encode() pipes the frames to ffmpeg with the music.
"""
import json
import math
import os
import re
import subprocess

import cv2
import numpy as np


CANVAS = (1920, 1080)
DURATIONS = (10, 15, 20, 30)
IMAGE_EXTENSIONS = {'psd', 'psb', 'png', 'jpg', 'jpeg', 'tif', 'tiff', 'webp', 'bmp'}
MAX_LAYERS = 12             # more than this and the lowest ones are merged into the background
EFFECTS = ('wipe', 'slide', 'fade', 'pop', 'cut')
DIRECTIONS = ('left', 'right', 'up', 'down')
SPEEDS = {'slow': 1.5, 'normal': 1.0, 'fast': 0.6}
STOP_MOTION_FPS = 12.0      # "animated on twos": the stepping that reads as stop motion
PUSH_IN = 0.05              # how much larger the picture is by the last frame of a push-in


class ArtworkError(ValueError):
    """The file could not be turned into something to animate; the message
    is written for the editor who picked it."""


