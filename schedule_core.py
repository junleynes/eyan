def fps_for(fmt_key):
    """(numerator, denominator) the frames are drawn at for a delivery
    format: the format's own rate, so nothing is frame-rate converted (a
    wipe converted from 29.97 to 23.976 judders)."""
    return (24000, 1001) if str(fmt_key or '').endswith('2398') else (30000, 1001)


def build_encode_cmd(ffmpeg, out_path, canvas, fps, duration, music_path=None, music_start=0.0,
                     loudness=-14.0, true_peak=-1.5):
    """ffmpeg command for the master: raw BGR frames on stdin, music (or
    silence) alongside, H.264 at near-lossless quality with PCM audio in a
    .mov -- an intermediate that the delivery formats are then made from.

    The frames are full-range RGB, as images are; the conversion to
    broadcast-range BT.709 is spelled out rather than left to defaults,
    which is the difference between the designer's colours and slightly
    washed-out ones."""
    w, h = canvas
    cmd = [ffmpeg, '-y', '-hide_banner', '-nostats', '-loglevel', 'error',
           '-f', 'rawvideo', '-pix_fmt', 'bgr24', '-s', f'{w}x{h}', '-r', f'{fps[0]}/{fps[1]}', '-i', 'pipe:0']
    if music_path:
        # Looped, so a sting shorter than the plug still covers it; trimmed
        # and faded below, so a track longer than it ends cleanly.
        cmd += ['-stream_loop', '-1', '-ss', f'{max(0.0, float(music_start)):.3f}', '-i', music_path]
        fade = min(1.5, duration / 4.0)
        audio = (f'[1:a:0]atrim=0:{duration:.3f},asetpts=PTS-STARTPTS,aresample=48000,'
                 f'afade=t=in:st=0:d=0.05,afade=t=out:st={duration - fade:.3f}:d={fade:.3f},'
                 f'loudnorm=I={loudness}:TP={true_peak}:LRA=11,aresample=48000[aout]')
    else:
        cmd += ['-f', 'lavfi', '-t', f'{duration:.3f}', '-i', 'anullsrc=channel_layout=stereo:sample_rate=48000']
        audio = '[1:a:0]anull[aout]'
    video = ('[0:v]scale=in_range=pc:out_range=tv:in_color_matrix=bt709:out_color_matrix=bt709:flags=lanczos,'
             'format=yuv420p,setsar=1[vout]')
    cmd += ['-filter_complex', f'{video};{audio}', '-map', '[vout]', '-map', '[aout]',
            '-t', f'{duration:.3f}',
            '-c:v', 'libx264', '-preset', 'medium', '-crf', '12', '-pix_fmt', 'yuv420p', '-profile:v', 'high',
            '-colorspace', 'bt709', '-color_primaries', 'bt709', '-color_trc', 'bt709', '-color_range', 'tv',
            '-c:a', 'pcm_s16le', '-ar', '48000', '-ac', '2', out_path]
    return cmd


class EncodeError(RuntimeError):
    pass


def encode(animator, out_path, fps, duration, ffmpeg='ffmpeg', music_path=None, music_start=0.0,
           loudness=-14.0, true_peak=-1.5, progress=None, timeout=1800):
    """Draws every frame and pipes it to ffmpeg. Returns the frame count.

    `progress(done, total)` is called every few frames; whatever it raises
    (a cancelled job) stops the encode and removes the partial file."""
    total = int(round(duration * fps[0] / float(fps[1])))
    cmd = build_encode_cmd(ffmpeg, out_path, animator.canvas, fps, duration, music_path, music_start,
                           loudness, true_peak)
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
    err = b''
    try:
        try:
            for n in range(total):
                proc.stdin.write(animator.frame(n * fps[1] / float(fps[0])).tobytes())
                if progress and (n % 10 == 0 or n == total - 1):
                    progress(n + 1, total)
        except (BrokenPipeError, OSError):
            pass                                    # ffmpeg stopped reading: its own message says why
        try:
            proc.stdin.close()
        except OSError:
            pass
        proc.stdin = None                           # closed by hand; communicate() must not touch it
        try:
            _, err = proc.communicate(timeout=timeout)
        except subprocess.TimeoutExpired as e:
            raise EncodeError(f'encoding did not finish within {timeout}s') from e
    except BaseException:
        proc.kill()
        proc.wait()
        if os.path.exists(out_path):
            try:
                os.remove(out_path)
            except OSError:
                pass
        raise
    if proc.returncode != 0 or not (os.path.exists(out_path) and os.path.getsize(out_path) > 0):
        if os.path.exists(out_path):
            try:
                os.remove(out_path)
            except OSError:
                pass
        text = ' | '.join(ln.strip() for ln in err.decode('utf-8', 'replace').splitlines() if ln.strip())
        raise EncodeError(text[:600] or f'ffmpeg exited with code {proc.returncode}')
    return total
